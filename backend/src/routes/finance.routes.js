const { Router } = require('express')
const { authUser } = require('../middlewares/auth.middleware')
const controller = require('../controllers/finance.controller')

const router = Router()
router.use(authUser)
router.get('/dashboard', controller.dashboard)
router.get('/forecasts', controller.forecasts)
router.get('/reports', controller.reports)
router.get('/transactions', controller.listTransactions)
router.post('/transactions', controller.createTransaction)
router.put('/transactions/:id', controller.updateTransaction)
router.delete('/transactions/:id', controller.deleteTransaction)
router.get('/budgets', controller.listBudgets)
router.post('/budgets', controller.saveBudget)
router.put('/budgets/:id', controller.saveBudget)
router.delete('/budgets/:id', controller.deleteBudget)
router.get('/loans', controller.listLoans)
router.post('/loans', controller.saveLoan)
router.put('/loans/:id', controller.saveLoan)
router.delete('/loans/:id', controller.deleteLoan)
router.post('/loans/:id/payments', controller.recordLoanPayment)

module.exports = router
